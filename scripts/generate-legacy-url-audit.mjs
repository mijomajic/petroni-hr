import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createClient } from '@supabase/supabase-js';

const root = process.cwd();
const legacyOrigin = 'https://www.petroni.hr';
const capturedOn = process.env.LEGACY_AUDIT_DATE ?? new Date().toISOString().slice(0, 10);
const snapshotPath = resolve(root, `docs/go-live/legacy-wordpress-sitemaps-${capturedOn}.json`);
const productDecisionsPath = resolve(root, 'src/lib/legacy-product-decisions.generated.ts');

function parseEnvironment(source) {
  const values = {};
  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator < 1) continue;
    const name = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[name] = value;
  }
  return values;
}

async function fetchText(url, attempt = 1) {
  try {
    const response = await fetch(url, {
      headers: { 'user-agent': 'Petroni go-live legacy URL audit/1.0' },
      signal: AbortSignal.timeout(30_000)
    });
    if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
    return { body: await response.text(), status: response.status, headers: response.headers };
  } catch (error) {
    if (attempt >= 4) throw new Error(`Could not fetch ${url}: ${error}`);
    await new Promise((resolveDelay) => setTimeout(resolveDelay, attempt * 750));
    return fetchText(url, attempt + 1);
  }
}

function xmlLocations(xml) {
  return [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)]
    .map((match) => match[1].replaceAll('&amp;', '&'));
}

async function mapConcurrent(items, concurrency, operation) {
  const results = new Array(items.length);
  let cursor = 0;
  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, async () => {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      results[index] = await operation(items[index], index);
    }
  }));
  return results;
}

async function fetchStoreProducts(language) {
  const query = (page) => `${legacyOrigin}/wp-json/wc/store/v1/products?per_page=100&page=${page}&_fields=slug,sku&lang=${language}`;
  const first = await fetchText(query(1));
  const firstResponse = JSON.parse(first.body);
  const totalPages = Number(first.headers.get('x-wp-totalpages') ?? '1');
  const pages = Array.from({ length: Math.max(totalPages - 1, 0) }, (_, index) => index + 2);
  const remaining = await mapConcurrent(pages, 3, async (page) => JSON.parse((await fetchText(query(page))).body));
  return [...firstResponse, ...remaining.flat()];
}

async function getAllProducts(client) {
  const products = [];
  for (let start = 0; ; start += 1000) {
    const { data, error } = await client
      .from('products')
      .select('slug,sku,is_active')
      .order('id')
      .range(start, start + 999);
    if (error) throw error;
    products.push(...(data ?? []));
    if ((data ?? []).length < 1000) return products;
  }
}

function productSlugFromUrl(value) {
  const path = new URL(value).pathname.replace(/\/+$/, '');
  return path.match(/^\/(?:proizvod|en\/product)\/([^/]+)$/)?.[1];
}

function generatedProductModule(aliases, goneSlugs, metadata) {
  const aliasLines = [...aliases.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([from, to]) => `  ${JSON.stringify(from)}: ${JSON.stringify(to)}`);
  const goneLines = [...goneSlugs]
    .sort((left, right) => left.localeCompare(right))
    .map((slug) => `  ${JSON.stringify(slug)}`);

  return `// Generated by scripts/generate-legacy-url-audit.mjs on ${capturedOn}.\n`
    + `// Source: ${legacyOrigin}/sitemap_index.xml and WooCommerce Store API.\n`
    + '// Do not edit by hand; regenerate after the final WordPress catalogue freeze.\n\n'
    + `export const LEGACY_PRODUCT_AUDIT = ${JSON.stringify(metadata, null, 2)} as const;\n\n`
    + 'export const legacyProductAliases: Readonly<Record<string, string>> = {\n'
    + `${aliasLines.join(',\n')}\n};\n\n`
    + 'export const goneLegacyProductSlugs = new Set<string>([\n'
    + `${goneLines.join(',\n')}\n]);\n`;
}

const environment = parseEnvironment(await readFile(resolve(root, '.env'), 'utf8'));
if (!environment.PUBLIC_SUPABASE_URL || !environment.SUPABASE_SERVICE_KEY) {
  throw new Error('PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_KEY are required locally to build the audited product map.');
}

const indexUrl = `${legacyOrigin}/sitemap_index.xml`;
const index = await fetchText(indexUrl);
const sitemapUrls = xmlLocations(index.body);
const sitemapSnapshots = await mapConcurrent(sitemapUrls, 2, async (url) => {
  const response = await fetchText(url);
  return {
    name: new URL(url).pathname.split('/').filter(Boolean).at(-1),
    source_url: url,
    http_status: response.status,
    urls: xmlLocations(response.body)
  };
});

const productSitemapUrls = sitemapSnapshots
  .filter((sitemap) => sitemap.name?.startsWith('product-sitemap'))
  .flatMap((sitemap) => sitemap.urls);
const productSlugs = new Set(productSitemapUrls.map(productSlugFromUrl).filter(Boolean));

const [croatianStoreProducts, englishStoreProducts, databaseProducts] = await Promise.all([
  fetchStoreProducts('hr'),
  fetchStoreProducts('en'),
  getAllProducts(createClient(environment.PUBLIC_SUPABASE_URL, environment.SUPABASE_SERVICE_KEY, {
    auth: { autoRefreshToken: false, persistSession: false }
  }))
]);

const wordpressBySlug = new Map(
  [...croatianStoreProducts, ...englishStoreProducts]
    .filter((product) => product.slug)
    .map((product) => [product.slug, product])
);
const databaseBySlug = new Map(databaseProducts.map((product) => [product.slug, product]));
const databaseBySku = new Map(databaseProducts.filter((product) => product.sku).map((product) => [product.sku, product]));
const aliases = new Map();
const goneSlugs = new Set();
let directProducts = 0;

for (const oldSlug of productSlugs) {
  const sameSlug = databaseBySlug.get(oldSlug);
  const wordpressProduct = wordpressBySlug.get(oldSlug);
  const skuMatch = wordpressProduct?.sku ? databaseBySku.get(wordpressProduct.sku) : undefined;
  const target = sameSlug?.is_active ? sameSlug : skuMatch?.is_active ? skuMatch : undefined;

  if (!target) {
    goneSlugs.add(oldSlug);
  } else if (target.slug === oldSlug) {
    directProducts += 1;
  } else {
    aliases.set(oldSlug, target.slug);
  }
}

const auditMetadata = {
  captured_on: capturedOn,
  sitemap_product_urls: productSitemapUrls.length,
  unique_product_slugs: productSlugs.size,
  direct_product_targets: directProducts,
  aliased_product_targets: aliases.size,
  gone_product_targets: goneSlugs.size,
  database_products: databaseProducts.length,
  active_database_products: databaseProducts.filter((product) => product.is_active).length
};

const snapshot = {
  version: 1,
  captured_on: capturedOn,
  source_index: indexUrl,
  source_index_http_status: index.status,
  note: 'Immutable pre-cutover sitemap inventory. Regenerate only for a new dated freeze; do not overwrite historical evidence.',
  summary: {
    sitemap_count: sitemapSnapshots.length,
    url_count: sitemapSnapshots.reduce((total, sitemap) => total + sitemap.urls.length, 0),
    unique_url_count: new Set(sitemapSnapshots.flatMap((sitemap) => sitemap.urls)).size,
    ...auditMetadata
  },
  sitemaps: sitemapSnapshots
};

await mkdir(resolve(root, 'docs/go-live'), { recursive: true });
await Promise.all([
  writeFile(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`),
  writeFile(productDecisionsPath, generatedProductModule(aliases, goneSlugs, auditMetadata))
]);

console.log(JSON.stringify({ snapshot: snapshotPath, generated_module: productDecisionsPath, summary: snapshot.summary }, null, 2));
